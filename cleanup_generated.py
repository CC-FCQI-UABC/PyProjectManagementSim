#!/usr/bin/env python3
"""
Cleanup script for files generated by the ABP simulator.

This script removes temporary files and results generated
during simulations to keep the project clean.

Paths are resolved against the project folder (where this script lives),
not the current working directory. Virtual environments and hidden folders
(.venv, .git, .idea, ...) are never touched.
"""

import os
import glob
import shutil
from pathlib import Path
from typing import Optional

PROJECT_ROOT = Path(__file__).resolve().parent

# Generated outputs, relative to the project root (non-recursive)
OUTPUT_PATTERNS = [
    "core/generated/*.csv",
    "core/generated/*.json",
    "core/generated/*.txt",
    "core/generated/*.html",
    "results/*.csv",
    "results/*.json",
    "results/*.txt",
    "charts_*",
    "*.log",
]

# Folders skipped when looking for Python caches
SKIPPED_DIRS = {"venv", "env", "node_modules"}


def _python_caches(root: Path):
    """Yield __pycache__ folders and stray .pyc files, skipping hidden folders and virtualenvs."""
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if not d.startswith(".") and d not in SKIPPED_DIRS]
        if "__pycache__" in dirnames:
            dirnames.remove("__pycache__")
            yield Path(dirpath) / "__pycache__"
        for filename in filenames:
            if filename.endswith(".pyc"):
                yield Path(dirpath) / filename


def cleanup_generated_files(root: Optional[Path] = None):
    """Cleans up files generated by the simulator under `root` (default: the project folder)."""
    root = Path(root) if root is not None else PROJECT_ROOT

    cleaned_files = []
    cleaned_dirs = []

    print(f"Starting cleanup of generated files in {root} ...")

    matches = [Path(m) for pattern in OUTPUT_PATTERNS for m in glob.glob(str(root / pattern))]
    matches += list(_python_caches(root))

    for match in matches:
        try:
            if match.is_file():
                match.unlink()
                cleaned_files.append(match)
                print(f"  File removed: {match.relative_to(root)}")

            elif match.is_dir():
                shutil.rmtree(match)
                cleaned_dirs.append(match)
                print(f"  Directory removed: {match.relative_to(root)}")

        except Exception as e:
            print(f"  Error removing {match}: {e}")

    # Create required directories if they don't exist
    required_dirs = ["core/generated", "results"]
    for dir_path in required_dirs:
        (root / dir_path).mkdir(parents=True, exist_ok=True)
        print(f"  Directory created/maintained: {dir_path}")

    print(f"\nCleanup completed:")
    print(f"  Files removed: {len(cleaned_files)}")
    print(f"  Directories removed: {len(cleaned_dirs)}")
    return cleaned_files, cleaned_dirs


if __name__ == "__main__":
    cleanup_generated_files()
